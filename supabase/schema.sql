-- 6.2 Registrar consumo individual de cantina con Servicio de Invitado y stock atómico
CREATE OR REPLACE FUNCTION public.registrar_consumo_cantina(
  p_socio_nombre text,
  p_socio_id bigint,
  p_detalle text,
  p_monto numeric,
  p_pagado boolean,
  p_metodo_pago text DEFAULT NULL,
  p_mesa text DEFAULT NULL,
  p_productos_usados jsonb DEFAULT '[]'::jsonb,
  p_es_invitado boolean DEFAULT false,
  p_observacion_invitado text DEFAULT NULL
)
RETURNS public.consumos_individuales
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_consumo_id text;
  v_now_ar timestamp;
  v_fecha_ar date;
  v_hora_ar text;
  v_item jsonb;
  v_consumo public.consumos_individuales%ROWTYPE;
